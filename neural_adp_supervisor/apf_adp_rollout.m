function [episode,summary] = apf_adp_rollout(item,mode,actorNet,cfg,s)
% Paired baseline and supervisor share every plant, APF, safety and goal check.
% Unlike the training environment, a baseline stall is not an early termination.
    p=item.parameters; obstacles=item.obstacles; state=item.initialState;
    [backup,canStop]=adp3d_braking_plan(state,obstacles,p,cfg.safety);
    assert(canStop,'APFADP:InitialStateCannotStop');
    limit=round(s.maximumFlightSeconds/p.dt);
    decisionLimit=ceil(limit/cfg.physicsStepsPerDecision);
    states=zeros(6,limit+1); states(:,1)=state;
    commands=zeros(3,limit); accelerations=commands;
    interventions=false(1,limit); obstacleDistances=inf(1,limit);
    boundaryMargins=inf(1,limit); modes=zeros(1,decisionLimit);
    waypoints=zeros(3,decisionLimit); actions=waypoints;
    decisionMilliseconds=zeros(1,decisionLimit); physicalMilliseconds=zeros(1,limit);
    diagnostics=cell(1,decisionLimit); controller=apf_adp_init();
    collision=false; termination='flight_timeout'; count=0; decision=0;
    clock=tic;
    while count<limit
        decision=decision+1; time=count*p.dt;
        timer=tic;
        if strcmp(mode,'automatic')
            [waypoint,controller,detail]=apf_adp_decide(controller,states(:,1:count+1), ...
                time,obstacles,p,cfg,s,actorNet);
        else
            waypoint=p.target;
            detail=struct('action',zeros(3,1));
        end
        decisionMilliseconds(decision)=1000*toc(timer);
        modes(decision)=controller.mode; waypoints(:,decision)=waypoint;
        actions(:,decision)=detail.action; diagnostics{decision}=detail;
        done=false;
        for micro=1:cfg.physicsStepsPerDecision
            if count>=limit, break; end
            timer=tic;
            if controller.mode==5
                command=-state(4:6)/p.dt;
            else
                command=adp3d_leader_command(state,waypoint,obstacles,p);
            end
            [next,backup,stepInfo]=adp3d_safe_step(state,command,backup,obstacles,p,cfg.safety);
            physicalMilliseconds(count+1)=1000*toc(timer);
            count=count+1; states(:,count+1)=next;
            commands(:,count)=stepInfo.executedCommand;
            accelerations(:,count)=stepInfo.actualAcceleration;
            interventions(count)=stepInfo.intervention;
            obstacleDistances(count)=stepInfo.minimumObstacleDistance;
            lo=p.workspace(1,:)'+cfg.safety.boundaryBuffer;
            hi=p.workspace(2,:)'-cfg.safety.boundaryBuffer;
            boundaryMargins(count)=min([next(1:3)-lo;hi-next(1:3)]);
            collision=collision || stepInfo.collision || stepInfo.boundaryHit;
            state=next;
            if collision
                termination='collision'; done=true;
            elseif norm(p.target-state(1:3))<=p.goalTol && norm(state(4:6))<=p.vTol
                termination='goal'; done=true;
            elseif controller.mode==5 && norm(state(4:6))<=cfg.safety.stopSpeed
                termination=controller.failureReason; done=true;
            end
            if done, break; end
        end
        if done, break; end
    end
    states=states(:,1:count+1);
    events=controller.events;
    cycleMilliseconds=physicalMilliseconds(1:count);
    decisionSteps=1:cfg.physicsStepsPerDecision:count;
    cycleMilliseconds(decisionSteps)=cycleMilliseconds(decisionSteps)+decisionMilliseconds(1:decision);
    activeDecisionTimes=decisionMilliseconds(modes(1:decision)==2);
    if isempty(activeDecisionTimes), activeDecisionTimes=0; end
    summary=struct('id',item.id,'family',item.family,'seed',item.seed,'split',item.split, ...
        'mode',mode,'success',strcmp(termination,'goal'),'termination',termination, ...
        'collision',collision,'flightSeconds',count*p.dt,'steps',count,'decisions',decision, ...
        'activations',controller.activations,'actorCalls',controller.actorCalls, ...
        'localExits',sum(strcmp({events.reason},'local_apf_corridor_clear')), ...
        'terminalExits',sum(strcmp({events.reason},'terminal_handoff')), ...
        'cooldownCompletions',sum(strcmp({events.reason},'cooldown_complete')), ...
        'finalGoalDistance',norm(p.target-state(1:3)),'finalSpeed',norm(state(4:6)), ...
        'pathLengthMeters',sum(vecnorm(diff(states(1:3,:),1,2),2,1)), ...
        'interventions',sum(interventions(1:count)), ...
        'hardObstacleMargin',min(obstacleDistances(1:count))-p.obsSafe, ...
        'boundaryMargin',min(boundaryMargins(1:count)), ...
        'maximumSpeed',max(vecnorm(states(4:6,:),2,1)), ...
        'maximumAcceleration',max(vecnorm(accelerations(:,1:count),2,1)), ...
        'adpSeconds',sum(modes(1:decision)==2)*cfg.physicsStepsPerDecision*p.dt, ...
        'decisionP99Milliseconds',prctile(decisionMilliseconds(1:decision),99), ...
        'decisionMaxMilliseconds',max(decisionMilliseconds(1:decision)), ...
        'activeDecisionP99Milliseconds',prctile(activeDecisionTimes,99), ...
        'activeDecisionMaxMilliseconds',max(activeDecisionTimes), ...
        'physicsP99Milliseconds',prctile(physicalMilliseconds(1:count),99), ...
        'physicsMaxMilliseconds',max(physicalMilliseconds(1:count)), ...
        'controlCycleP99Milliseconds',prctile(cycleMilliseconds,99), ...
        'controlCycleMaxMilliseconds',max(cycleMilliseconds), ...
        'controlCyclesOver50Milliseconds',sum(cycleMilliseconds>50), ...
        'decisionsOver200Milliseconds',sum(decisionMilliseconds(1:decision)>200), ...
        'wallSeconds',toc(clock));
    episode=struct('item',item,'states',states,'commands',commands(:,1:count), ...
        'accelerations',accelerations(:,1:count),'interventions',interventions(1:count), ...
        'minimumObstacleDistances',obstacleDistances(1:count),'modes',modes(1:decision), ...
        'waypoints',waypoints(:,1:decision),'actions',actions(:,1:decision), ...
        'events',events,'diagnostics',{diagnostics(1:decision)}, ...
        'decisionMilliseconds',decisionMilliseconds(1:decision), ...
        'physicalMilliseconds',physicalMilliseconds(1:count), ...
        'controlCycleMilliseconds',cycleMilliseconds,'summary',summary);
end
