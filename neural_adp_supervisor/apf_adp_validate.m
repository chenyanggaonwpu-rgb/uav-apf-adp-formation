function report = apf_adp_validate(split,outputDirectory)
% Run once per declared split; writes protocol before any controller rollout.
    s=apf_adp_config(); addpath(fullfile(s.projectRoot,'neural_adp3d'));
    cfg=adp3d_config('train'); cfg.plots='none';
    p=adp3d_setup(cfg);
    loaded=load(s.modelFile,'actorNet','metadata'); actorNet=loaded.actorNet;
    assert(isequaln(loaded.metadata.sourceManifest,adp3d_source_manifest(cfg)), ...
        'APFADP:FrozenSourceChanged');
    assert(loaded.metadata.scanRange==cfg.scanRange && loaded.metadata.maxOffset==cfg.maxOffset ...
        && loaded.metadata.decisionPeriod==cfg.physicsStepsPerDecision*p.dt);
    originalWeights=actorNet.Learnables;
    cases=apf_adp_cases(split,cfg,s);
    protocol=struct('version',s.version,'split',split,'caseCount',numel(cases), ...
        'caseIds',{cellfun(@(x)x.id,cases,'UniformOutput',false)}, ...
        'modelFile',s.modelFile,'settings',s,'scope','single UAV, known static map, no noise or disturbance', ...
        'pairedBaseline','identical original APF, dynamics, safety, initial state, horizon and goal test', ...
        'falseActivationDefinition','any activation in a case where paired pure APF succeeds', ...
        'caseSelection','all predeclared cases retained, no filtering by flight result', ...
        'heldoutSeeds',20001:20016,'freshNormalSeeds',50001:50024);
    save(fullfile(outputDirectory,'protocol.mat'),'protocol','cases','cfg','s','-v7');
    writeJson('protocol.json',protocol);
    checks=apf_adp_checks(actorNet,cfg,s); writeJson('controller_checks.json',checks);
    % Warm the small inference graph without moving a simulated UAV or updating weights.
    adp3d_actor_action(actorNet,zeros(32,1));
    % Compile the paired rollout loop on a separate, declared empty warmup, never a test map.
    warmP=p; warmP.start=[10;10;10]; warmP.target=[70;62;10];
    warmScene=scenario3d('S0_empty',0,warmP); warmSettings=s; warmSettings.maximumFlightSeconds=0.4;
    warmItem=struct('id','timing_warmup','family','empty_warmup','seed',0,'split','warmup', ...
        'parameters',warmP,'obstacles',warmScene.obstacles,'initialState',[warmP.start;zeros(3,1)]);
    apf_adp_rollout(warmItem,'apf',actorNet,cfg,warmSettings);
    apf_adp_rollout(warmItem,'automatic',actorNet,cfg,warmSettings);
    summaries={}; pairs={}; eventRows={};
    for k=1:numel(cases)
        item=cases{k};
        [baseline,baseSummary]=apf_adp_rollout(item,'apf',actorNet,cfg,s);
        [automatic,autoSummary]=apf_adp_rollout(item,'automatic',actorNet,cfg,s);
        save(fullfile(outputDirectory,[item.id '_apf.mat']),'baseline','baseSummary','-v7');
        save(fullfile(outputDirectory,[item.id '_automatic.mat']),'automatic','autoSummary','-v7');
        summaries{end+1}=baseSummary; summaries{end+1}=autoSummary; %#ok<AGROW>
        aligned=min(size(baseline.states,2),size(automatic.states,2));
        difference=max(vecnorm(baseline.states(:,1:aligned)-automatic.states(:,1:aligned),2,1));
        exact=isequal(baseline.states,automatic.states) && isequal(baseline.commands,automatic.commands);
        pair=struct('id',item.id,'family',item.family,'seed',item.seed, ...
            'apfSuccess',baseSummary.success,'automaticSuccess',autoSummary.success, ...
            'apfTermination',baseSummary.termination,'automaticTermination',autoSummary.termination, ...
            'activations',autoSummary.activations,'localExits',autoSummary.localExits, ...
            'terminalExits',autoSummary.terminalExits,'falseActivation',baseSummary.success && autoSummary.activations>0, ...
            'lostAPFSuccess',baseSummary.success && ~autoSummary.success, ...
            'exactSameTrajectoryAndCommands',exact,'maximumAlignedStateDifference',difference, ...
            'flightSecondsDifference',autoSummary.flightSeconds-baseSummary.flightSeconds, ...
            'pathLengthDifference',autoSummary.pathLengthMeters-baseSummary.pathLengthMeters, ...
            'automaticCollision',autoSummary.collision,'automaticInterventions',autoSummary.interventions, ...
            'automaticHardMargin',autoSummary.hardObstacleMargin);
        pairs{end+1}=pair; %#ok<AGROW>
        for e=1:numel(automatic.events)
            event=automatic.events(e); position=event.position; event=rmfield(event,'position');
            event.id=item.id; event.x=position(1); event.y=position(2); event.z=position(3);
            eventRows{end+1}=event; %#ok<AGROW>
        end
        assert(~autoSummary.collision && ~baseSummary.collision,'APFADP:CollisionObserved');
        assert(autoSummary.maximumSpeed<=p.vmax+1e-8 && autoSummary.maximumAcceleration<=p.amax+1e-8);
        if autoSummary.activations==0
            assert(exact && autoSummary.actorCalls==0,'APFADP:APFInterferenceWithoutActivation');
        end
        allRows=struct2table([summaries{:}]); pairRows=struct2table([pairs{:}]);
        writetable(allRows,fullfile(outputDirectory,'all_cases.csv'));
        writetable(pairRows,fullfile(outputDirectory,'paired_cases.csv'));
        if ~isempty(eventRows), writetable(struct2table([eventRows{:}]),fullfile(outputDirectory,'all_events.csv')); end
        fprintf('PAIR %d/%d %s: APF=%d AUTO=%d trigger=%d exit=%d+%d t=%.2f collision=%d\n', ...
            k,numel(cases),item.id,baseSummary.success,autoSummary.success,autoSummary.activations, ...
            autoSummary.localExits,autoSummary.terminalExits,autoSummary.flightSeconds,autoSummary.collision);
    end
    assert(isequaln(originalWeights,actorNet.Learnables),'APFADP:ActorWeightsChanged');
    baselineRows=allRows(strcmp(allRows.mode,'apf'),:);
    automaticRows=allRows(strcmp(allRows.mode,'automatic'),:);
    traps=strcmp(pairRows.family,'approach_window'); normal=pairRows.apfSuccess;
    report=struct('split',split,'scope',protocol.scope,'outputDirectory',outputDirectory, ...
        'cases',numel(cases),'apfSuccessCount',sum(pairRows.apfSuccess), ...
        'automaticSuccessCount',sum(pairRows.automaticSuccess),'collisionCount',sum(allRows.collision), ...
        'windowCases',sum(traps),'windowAPFSuccesses',sum(pairRows.apfSuccess(traps)), ...
        'windowAutomaticSuccesses',sum(pairRows.automaticSuccess(traps)), ...
        'windowCasesTriggered',sum(pairRows.activations(traps)>0), ...
        'apfSuccessfulCases',sum(normal),'falseActivationCases',sum(pairRows.falseActivation), ...
        'lostAPFSuccesses',sum(pairRows.lostAPFSuccess), ...
        'apfSuccessfulCasesExactlyPreserved',sum(normal & pairRows.exactSameTrajectoryAndCommands), ...
        'casesWithLocalExit',sum(pairRows.localExits>0),'casesWithReactivation',sum(pairRows.activations>1), ...
        'casesEndingEscapeTimeout',sum(strcmp(automaticRows.termination,'escape_timeout')), ...
        'baselineInterventions',sum(baselineRows.interventions), ...
        'automaticInterventions',sum(automaticRows.interventions), ...
        'minimumHardObstacleMargin',min(allRows.hardObstacleMargin), ...
        'minimumBoundaryMargin',min(allRows.boundaryMargin), ...
        'maximumSpeed',max(allRows.maximumSpeed),'maximumAcceleration',max(allRows.maximumAcceleration), ...
        'maximumSupervisorDecisionMilliseconds',max(automaticRows.decisionMaxMilliseconds), ...
        'maximumPhysicsStepMilliseconds',max(allRows.physicsMaxMilliseconds), ...
        'automaticControlCycles',sum(automaticRows.steps), ...
        'automaticControlCyclesOver50Milliseconds',sum(automaticRows.controlCyclesOver50Milliseconds), ...
        'maximumAutomaticControlCycleMilliseconds',max(automaticRows.controlCycleMaxMilliseconds), ...
        'automaticDecisionsOver200Milliseconds',sum(automaticRows.decisionsOver200Milliseconds), ...
        'weightsUnchanged',true,'trainingPerformed',false,'allCasesRetained',true);
    writeJson('report.json',report);
    save(fullfile(outputDirectory,'validation.mat'),'report','allRows','pairRows','checks','protocol','-v7');
    selected={cases{1}.id};
    if any(strcmp(protocol.caseIds,'sequential_windows_2')), selected{end+1}='sequential_windows_2'; end
    for k=1:numel(selected)
        a=load(fullfile(outputDirectory,[selected{k} '_automatic.mat']),'automatic');
        b=load(fullfile(outputDirectory,[selected{k} '_apf.mat']),'baseline');
        apf_adp_plot(a.automatic,b.baseline,fullfile(outputDirectory,[selected{k} '_flow']));
    end
    fprintf('SUPERVISOR_VALIDATION_COMPLETED\n');
    function writeJson(name,value)
        fid=fopen(fullfile(outputDirectory,name),'w','n','UTF-8');
        guard=onCleanup(@()fclose(fid)); %#ok<NASGU>
        fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));
    end
end
