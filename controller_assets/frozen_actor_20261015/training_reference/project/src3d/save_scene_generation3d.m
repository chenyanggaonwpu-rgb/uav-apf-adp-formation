function save_scene_generation3d(scene,outputDir)
% SAVE_SCENE_GENERATION3D Freeze accepted and rejected proposals before flight.
    metadata=scene.generation; audit=scene.generationAudit;
    save(fullfile(outputDir,'scene_generation.mat'),'scene','metadata','audit','-v7.3');
    rows=struct([]);
    for k=1:numel(audit.proposals)
        proposal=audit.proposals{k}; check=proposal.check; expanded=nan; duration=nan;
        if isfield(check.witness,'expandedNodes'), expanded=check.witness.expandedNodes; end
        if isfield(check.witness,'duration'), duration=check.witness.duration; end
        rows=[rows;struct('attempt',proposal.attempt,'proposalSeed',proposal.proposalSeed, ...
            'obstacleCount',proposal.samplingMetadata.obstacleCount, ...
            'accepted',check.accepted,'reason',string(check.reason), ...
            'initialClearance',check.initialClearance,'terminalClearance',check.terminalClearance, ...
            'endpointClearance',check.endpointClearance,'departureValid',check.departureValid, ...
            'arrivalValid',check.arrivalValid,'arrivalClearanceLowerBound',check.arrivalClearanceLowerBound, ...
            'departureClearanceLowerBound',check.departureClearanceLowerBound, ...
            'feasibilityStatus',string(check.feasibilityStatus),'expandedNodes',expanded, ...
            'witnessDuration',duration)]; %#ok<AGROW>
    end
    writetable(struct2table(rows),fullfile(outputDir,'generation_proposals.csv'));
    receipt=struct('protocol',audit.protocol,'requestedSeed',audit.requestedSeed, ...
        'accepted',audit.accepted,'attempts',audit.attempts,'rejectedMaps',audit.rejectedMaps, ...
        'acceptedProposalSeed',audit.acceptedProposalSeed,'options',audit.options, ...
        'metadata',metadata,'mapAndRejectionsFile','scene_generation.mat', ...
        'selectionRule',audit.selectionRule, ...
        'rateRule','Generation acceptance and complete-flight success have separate denominators.');
    file=fopen(fullfile(outputDir,'generation_receipt.json'),'w','n','UTF-8');
    assert(file>=0,'UAV3D:Output','Could not write generation receipt.');
    cleanup=onCleanup(@() fclose(file)); %#ok<NASGU>
    fprintf(file,'%s',jsonencode(receipt,PrettyPrint=true));
end
