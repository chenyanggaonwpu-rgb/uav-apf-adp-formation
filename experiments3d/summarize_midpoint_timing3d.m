function summarize_midpoint_timing3d(studyDir)
% SUMMARIZE_MIDPOINT_TIMING3D Timing from recorded runs, no extra simulations.
    saved=load(fullfile(studyDir,'protocol.mat'),'protocol'); protocol=saved.protocol;
    records=struct([]);
    for seed=protocol.seeds
        worker=find(seed>=protocol.ranges(:,1) & seed<=protocol.ranges(:,2));
        file=fullfile(studyDir,'workers',sprintf('worker_%02d',worker),'trials',sprintf('adaptive_%06d.mat',seed));
        d=load(file,'r','q'); r=d.r;
        cycles=zeros(0,1);
        if isfield(r.history,'cycleMs'), cycles=r.history.cycleMs(:);cycles=cycles(cycles>0);end
        med=nan; p95=nan; p99=nan; peak=nan;
        if ~isempty(cycles)
            sorted=sort(cycles);med=median(cycles);peak=sorted(end);
            p95=sorted(max(1,ceil(.95*numel(sorted))));p99=sorted(max(1,ceil(.99*numel(sorted))));
        end
        replan=r.timing.replanSeconds; terminal=r.timing.terminalPlanSeconds;
        records=[records;struct('seed',seed,'success',r.success,'initialPlanSeconds',r.timing.initialPlanSeconds, ...
            'measuredCycles',numel(cycles),'cycleDeadlineMs',1000*d.q.dt,'cyclesAboveDt',nnz(cycles>1000*d.q.dt), ...
            'medianCycleMs',med,'p95CycleMs',p95,'p99CycleMs',p99,'maxCycleMs',peak, ...
            'replanCalls',numel(replan),'maxReplanSeconds',max([0;replan(:)]), ...
            'terminalPlanCalls',numel(terminal),'maxTerminalPlanSeconds',max([0;terminal(:)]))]; %#ok<AGROW>
    end
    timing=struct2table(records);assert(height(timing)==1000 && numel(unique(timing.seed))==1000);
    writetable(timing,fullfile(studyDir,'timing_by_seed.csv'));
    initial=timing.initialPlanSeconds; sorted=sort(initial(isfinite(initial)));
    flight=timing.p99CycleMs(isfinite(timing.p99CycleMs));
    summary=struct('records',1000,'measuredCycles',sum(timing.measuredCycles), ...
        'cyclesAboveDt',sum(timing.cyclesAboveDt),'cycleDeadlineMs',1000*protocol.p.dt, ...
        'initialPlanMedianSeconds',median(initial,'omitnan'), ...
        'initialPlanP95Seconds',sorted(max(1,ceil(.95*numel(sorted)))), ...
        'initialPlanMaxSeconds',max(initial), ...
        'perFlightP99MedianMs',median(flight),'maxCycleMs',max(timing.maxCycleMs,[],'omitnan'), ...
        'maxReplanSeconds',max(timing.maxReplanSeconds),'maxTerminalPlanSeconds',max(timing.maxTerminalPlanSeconds), ...
        'quantileRule','Nearest rank for each run; median of per-flight P99 reported separately.', ...
        'timingScope','Recorded during four concurrent single-compute-thread MATLAB processes; not an isolated or hard real-time benchmark.');
    fid=fopen(fullfile(studyDir,'timing_summary.json'),'w','n','UTF-8');
    fprintf(fid,'%s',jsonencode(summary,PrettyPrint=true));fclose(fid);
    fprintf('MIDPOINT_TIMING_SUMMARY records=%d cycles=%d above_dt=%d\n', ...
        summary.records,summary.measuredCycles,summary.cyclesAboveDt);
end
