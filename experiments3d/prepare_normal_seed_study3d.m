function prepare_normal_seed_study3d(studyDir,sourceCommit,firstSeed,nSeeds,nWorkers)
% PREPARE_NORMAL_SEED_STUDY3D Predeclare a fixed, independent normal-scene trial.
    snap=fullfile(studyDir,'source_snapshot');
    addpath(fullfile(snap,'config'),fullfile(snap,'src3d'),fullfile(snap,'experiments3d'));
    assert(startsWith(which('default_params3d'),snap));
    p=default_params3d();p.sceneId='random_normal';p.animate=false;
    root=fileparts(fileparts(fileparts(snap)));p.resultsRoot=fullfile(root,'results');p.figDir=p.resultsRoot;
    p=validate_params3d(p);
    assert(strcmp(p.version,'2.3.3') && p.pathClearance==1.2 && p.desiredClear==4);
    assert(p.adaptiveHeight.enable && p.adaptiveHeight.maxAddedLayers==8);
    assert(p.noiseStd==0 && p.disturbanceMax==0 && p.adp.enable && p.safety.enable);
    assert(all(p.adp.wC==0,'all') && all(p.adp.wA==0,'all'));
    assert(nWorkers<=nSeeds && nSeeds>0);
    edges=floor(linspace(0,nSeeds,nWorkers+1));ranges=[firstSeed+edges(1:end-1)',firstSeed+edges(2:end)'-1];
    protocol=struct('version',p.version,'experiment','normal_random_full_flight', ...
        'p',p,'generation',p.normalScene,'seeds',firstSeed:firstSeed+nSeeds-1, ...
        'nSeeds',nSeeds,'nWorkers',nWorkers,'ranges',ranges,'sourceCommit',sourceCommit, ...
        'createdLocal',char(datetime('now','TimeZone','Asia/Shanghai','Format','yyyy-MM-dd HH:mm:ss')), ...
        'mapRule','Predeclared requested seeds; at most 100 whole-map proposals per seed; preserve every proposal and every generation failure; freeze all maps before any evaluated flight.', ...
        'selectionRule','Independent environment and fixed-V translation witness only; no evaluated flight-success filtering and no seed replacement.', ...
        'denominatorRule','Primary success / all requested seeds; separately success / accepted maps; generation acceptance / all raw proposals. Execution errors must be resolved before reporting.', ...
        'controllerRule','Unchanged release 2.3.3; independent default zero ADP weights and fresh planner cache for each flight; no parameter tuning.', ...
        'timingRule','Concurrent MATLAB processes, each single compute thread. Offline generation time and full-job wall time are distinct from simulated mission time and online planning time.', ...
        'successRule','Use the actual full-flight result.success; leader <=1 m, followers <=1 m to dynamic references, all speeds <=0.25 m/s, continuous hold >=1 s, within 120 s, without hard failure.', ...
        'modelScope','Noise-free five point-mass UAVs, initially airborne at 10 m and stationary; not a physical ground-takeoff or energy test.');
    save(fullfile(studyDir,'protocol.mat'),'protocol','-v7');
    normal_seed_study_io3d('json',fullfile(studyDir,'protocol.json'),protocol);
    fprintf('NORMAL_PROTOCOL_READY seeds=%d:%d n=%d workers=%d\n',firstSeed,firstSeed+nSeeds-1,nSeeds,nWorkers);
end
