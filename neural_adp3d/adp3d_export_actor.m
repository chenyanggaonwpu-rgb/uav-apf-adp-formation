function adp3d_export_actor(agent,cfg,sourceManifest,file,episodes)
% 只导出推理所需 Actor，不带 Critic、经验池或在线训练器。
    actorNet=getModel(getActor(agent));
    actorNet=dlupdate(@gather,actorNet);
    metadata=struct('interfaceVersion',cfg.interfaceVersion,'observationSize',32, ...
        'actionSize',3,'scanRange',cfg.scanRange,'maxOffset',cfg.maxOffset, ...
        'decisionPeriod',0.05*cfg.physicsStepsPerDecision, ...
        'completedTrainingEpisodes',episodes,'policyValidated',false, ...
        'mode',cfg.mode,'formalTraining',strcmp(cfg.mode,'train'), ...
        'observationDefinition','[goalError/goalScale; velocity/vmax; scan26/range]', ...
        'actionDefinition','world-frame xyz offset, projected to unit ball, then scaled', ...
        'requiresExternalSafetyGuard',true,'sourceManifest',sourceManifest); %#ok<NASGU>
    save(file,'actorNet','metadata','-v7');
end
