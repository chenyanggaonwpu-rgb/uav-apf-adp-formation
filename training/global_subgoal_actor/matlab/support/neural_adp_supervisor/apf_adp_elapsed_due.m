function due=apf_adp_elapsed_due(controller,time,s)
% A one-shot mission-time fallback, shared by learned and rule proposals.
    due=isfield(s,'elapsedTakeover') && s.elapsedTakeover.enable && ...
        ~controller.elapsedTakeoverUsed && time>=s.elapsedTakeover.afterSeconds-1e-9 && ...
        controller.mode~=2 && controller.mode~=3 && controller.mode~=5 && ...
        controller.activations<s.maximumActivations;
end
