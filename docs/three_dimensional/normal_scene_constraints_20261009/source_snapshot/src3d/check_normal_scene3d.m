function report=check_normal_scene3d(scene,p,options)
% CHECK_NORMAL_SCENE3D Separate initial validity, departure, terminal validity and witness.
    if nargin<3, options=struct(); end
    rules=validate_normal_scene_options3d(p,options);
    [initial,~,~]=init_formation3d(p); start=initial(1:3,:);
    offsets=start-p.start; terminal=p.target+offsets;
    direction=p.target-p.start;
    assert(norm(direction)>1e-9,'UAV3D:NormalDepartureGeometry','Distinct endpoints are required.');
    departure=p.start+rules.departureLength*direction/norm(direction);
    arrival=p.target-rules.departureLength*direction/norm(direction);
    report=struct('accepted',false,'reason','not_checked','initialValid',false, ...
        'departureValid',false,'arrivalValid',false,'terminalValid',false,'endpointValid',false, ...
        'localValid',false,'taskFeasible',false,'feasibilityStatus','not_checked', ...
        'initialClearance',min(point_clearance_batch3d(start,scene.obstacles)), ...
        'terminalClearance',min(point_clearance_batch3d(terminal,scene.obstacles)), ...
        'endpointClearance',min(point_clearance_batch3d([p.start,p.target],scene.obstacles)), ...
        'initialBoundaryClearance',boundary_clearance(start), ...
        'terminalBoundaryClearance',boundary_clearance(terminal), ...
        'minPairDistance',inf,'departurePoint',departure,'arrivalPoint',arrival, ...
        'departureClearanceLowerBound',nan,'arrivalClearanceLowerBound',nan, ...
        'witness',struct('status','not_checked'));
    for i=1:p.nUAV-1
        for j=i+1:p.nUAV, report.minPairDistance=min(report.minPairDistance,norm(start(:,i)-start(:,j))); end
    end
    report.initialValid=report.initialClearance>=rules.startClearance && ...
        report.initialBoundaryClearance>=rules.boundaryClearance && report.minPairDistance>p.uavSafe;
    report.terminalValid=report.terminalClearance>=rules.terminalClearance && ...
        report.terminalBoundaryClearance>=rules.boundaryClearance;
    report.endpointValid=report.endpointClearance>=rules.endpointClearance;
    if ~report.initialValid, report.reason='initial_geometry'; return; end
    if ~report.terminalValid, report.reason='terminal_geometry'; return; end
    if ~report.endpointValid, report.reason='endpoint_clearance'; return; end
    [report.departureValid,report.departureClearanceLowerBound]= ...
        certify_formation_segment3d(p.start,departure,offsets,scene.obstacles,p, ...
        rules.departureClearance,rules.boundaryClearance,rules.certificateTolerance);
    if ~report.departureValid, report.reason='departure_not_certified'; return; end
    [report.arrivalValid,report.arrivalClearanceLowerBound]= ...
        certify_formation_segment3d(arrival,p.target,offsets,scene.obstacles,p, ...
        rules.departureClearance,rules.boundaryClearance,rules.certificateTolerance);
    if ~report.arrivalValid, report.reason='arrival_not_certified'; return; end
    report.localValid=true;
    if rules.requireWitness
        report.witness=formation_witness3d(departure,arrival,offsets,scene.obstacles,p,rules);
        report.feasibilityStatus=report.witness.status;
        report.taskFeasible=strcmp(report.feasibilityStatus,'certified');
        if ~report.taskFeasible, report.reason='witness_not_certified'; return; end
    end
    report.accepted=true; report.reason='accepted';
    function value=boundary_clearance(points)
        value=min([points-p.workspace(1,:)',p.workspace(2,:)'-points],[],'all');
    end
end
