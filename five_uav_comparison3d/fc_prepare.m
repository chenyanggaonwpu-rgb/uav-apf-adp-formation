function fc_prepare(project,campaign)
    [~,cfg,s,modelInfo]=rtadp_load_actor(project);
    loaded=load(fullfile(project,'results','planning_block_fix_20261013','inputs','trial_010001_S.mat'),'q');
    p=loaded.q;p.adp.enable=false;p.animate=false;
    assert(p.nUAV==5 && p.dt==.05 && p.Tmax==120 && p.noiseStd==0 && p.disturbanceMax==0);
    cases=fc_cases(p,cfg,'formal');pilotCases=fc_cases(p,cfg,'pilot');
    assert(numel(cases)==144 && numel(unique(cellfun(@(x)x.seed,cases)))==144);
    assert(isempty(intersect(cfg.trainSeeds,cellfun(@(x)x.seed,cases))));
    assert(isempty(intersect([cfg.validationSeeds cfg.testSeeds],cellfun(@(x)x.seed,cases))));
    protocol=struct('version','five-uav-factorial-comparison-v1','caseCount',144,'flightCount',864, ...
        'routePolicies',{{'global','local_apf'}},'methods',{{'none','rule','actor'}}, ...
        'families',struct('normal',48,'structured',24,'single_window',32,'double_window',24,'concave',8,'blocked',8), ...
        'fullMapKnown',true,'unknownEnvironmentClaim',false,'noiseAndDisturbance',false, ...
        'rule','26-ray clearance + goal alignment + direction hysteresis; local 32-vector only; no path search or case metadata', ...
        'ruleConstants',struct('rangeFraction',.85,'extraMarginMeters',.25,'goalWeight',.65,'directionWeight',.25,'minimumOffsetMeters',.75), ...
        'sameSupervisorConditions',true,'sameSafetyAndDynamics',true,'sameFiveUavCompletionRule',true, ...
        'noOutcomeTuning',true,'preserveEveryCase',true,'freshPlannerCachePerFlight',true, ...
        'order','Rotate the six combinations by predeclared case index; every combination executed once per case', ...
        'geometrySelection','Normal family retains original geometry-only conditioning and rejected proposals; all other families unfiltered by flight outcomes', ...
        'scope','Within-family new seeds; trained window geometry is not out-of-distribution evidence', ...
        'timingScope','Concurrent unpaced CPU processing is not serial latency or real-time evidence', ...
        'trainingPerformed',false,'criticLoaded',false,'modelInfo',modelInfo,'parameters',p,'configuration',cfg,'supervisor',s);
    save(fullfile(campaign,'catalogue_before_flight.mat'),'cases','pilotCases','protocol','-v7');
    fc_writejson(fullfile(campaign,'protocol.json'),protocol);
    index=struct([]);
    for i=1:numel(cases)
        item=cases{i};[state,~,~]=init_formation3d(item.parameters);
        [collision,~,~,~]=check_swept3d(state,state,item.scene.obstacles,item.parameters);
        generationFailed=strcmp(item.scene.kind,'generation_failed');
        index=[index;struct('index',i,'id',string(item.id),'family',string(item.family),'seed',item.seed, ...
            'obstacles',numel(item.scene.obstacles),'initialCollision',collision,'generationFailed',generationFailed)]; %#ok<AGROW>
        save(fullfile(campaign,'inputs',[item.id '.mat']),'item','-v7');
    end
    writetable(struct2table(index),fullfile(campaign,'catalogue.csv'));
    fc_writejson(fullfile(campaign,'prepare_completion.json'),struct('completed',true,'cases',numel(cases), ...
        'flights',6*numel(cases),'invalidInitial',sum([index.initialCollision]),'generationFailed',sum([index.generationFailed])));
    fprintf('FC_PREPARED cases=%d flights=%d initialInvalid=%d generationFailed=%d\n',numel(cases),6*numel(cases),sum([index.initialCollision]),sum([index.generationFailed]));
end
